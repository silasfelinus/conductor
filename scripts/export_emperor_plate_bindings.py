#!/usr/bin/env python3
"""Write Emperor of Dust's delivered-plate bindings from the curated art ledgers.

WHY THIS EXISTS. ``export_round_art.py`` ships each keeper to
``kind_robots/public/emperor-of-dust/<asset>.webp`` and can rebuild a flat list of
files, but chance-event, audience, quest-consequence and ending plates are bound to
game ids that only the ledger knows (``audience`` + ``variant``/``option``,
``quest`` + ``variant``). Before 2026-11-21 those ~300 keepers sat DONE in their
ledgers while ``EXPORTED_AUDIENCE_CHOICES`` and ``EXPORTED_CHANCE_PLATES`` stayed
empty. This writes one generated TypeScript module the game reads, listing only
plates that physically ship and carry a ``keep`` verdict (rejects never bind).

Usage:
    python scripts/export_emperor_plate_bindings.py --kind-robots ../kind_robots
    python scripts/export_emperor_plate_bindings.py --check   # exit 1 if stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
ART = ROOT / "projects" / "emperor-of-dust" / "art"
OUT = Path("utils/emperorOfDust/fortress/deliveredPlates.ts")
SCENE_VARIANTS = {"notice", "entrance", "enter", "intro", "introduction", "scene"}


def decision(subject: dict) -> str | None:
    verdict = str(subject.get("verdict") or "").strip().lower()
    if verdict.startswith("reject"):
        return "reject"
    if verdict.startswith("keep"):
        return "keep"
    return None


def keepers(art_dir: Path):
    for path in sorted(art_dir.glob("*.yaml")):
        data = yaml.safe_load(path.read_text()) or {}
        for subject in data.get("subjects") or []:
            if isinstance(subject, dict) and subject.get("asset") and decision(subject) == "keep":
                yield path.name, subject


def collect(art_dir: Path, kind_robots: Path) -> dict:
    public = kind_robots / "public" / "emperor-of-dust"
    chance, audience, quest, ending = set(), {}, {}, set()
    for _ledger, s in keepers(art_dir):
        asset = str(s["asset"])
        if not (public / f"{asset}.webp").is_file():
            continue
        head, _, rest = asset.partition("/")
        if head == "chance-events":
            chance.add(rest)
        elif head == "endings":
            ending.add(rest)
        elif head == "audiences" and s.get("quest"):
            quest.setdefault(f"{s['quest']}:{s.get('variant')}", rest)
        elif head == "audiences" and s.get("audience"):
            choice = str(s.get("option") or s.get("variant") or "")
            if choice in SCENE_VARIANTS:
                choice = "scene"
            audience.setdefault(f"{s['audience']}:{choice}", rest)
    return {"chance": sorted(chance), "audience": dict(sorted(audience.items())),
            "quest": dict(sorted(quest.items())), "ending": sorted(ending)}


def render(b: dict) -> str:
    def arr(name, doc, items):
        body = "".join(f"  '{i}',\n" for i in items)
        return f"/** {doc} */\nexport const {name}: readonly string[] = [\n{body}]\n"

    def rec(name, doc, items):
        body = "".join(f"  '{k}': '{v}',\n" for k, v in items.items())
        return (f"/** {doc} */\nexport const {name}: Readonly<Record<string, string>> = {{\n"
                f"{body}}}\n")

    return (
        "// Generated by conductor scripts/export_emperor_plate_bindings.py from the curated\n"
        "// projects/emperor-of-dust/art ledgers (keep verdicts whose WebP ships). Re-run; do not edit.\n\n"
        + arr("CHANCE_PLATES", "`<event>/<choice|notice>` under public/emperor-of-dust/chance-events/.",
              b["chance"]) + "\n"
        + rec("AUDIENCE_PLATES", "`<audience>:<option|scene>` -> file under public/emperor-of-dust/audiences/.",
              b["audience"]) + "\n"
        + rec("QUEST_OUTCOME_PLATES",
              "`<quest>:<success|partial|failure|expired>` -> file under public/emperor-of-dust/audiences/.",
              b["quest"]) + "\n"
        + arr("ENDING_PLATES", "Ending ids with a painted plate under public/emperor-of-dust/endings/.",
              b["ending"])
    )


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--kind-robots", default="../kind_robots")
    parser.add_argument("--art", default=str(ART))
    parser.add_argument("--check", action="store_true", help="exit 1 when the module is stale")
    args = parser.parse_args(argv)
    kr = Path(args.kind_robots)
    text = render(collect(Path(args.art), kr))
    dest = kr / OUT
    if args.check:
        current = dest.read_text() if dest.is_file() else ""
        if current != text:
            print(f"{dest} is stale; re-run without --check", file=sys.stderr)
            return 1
        print(f"{dest} up to date")
        return 0
    dest.write_text(text)
    print(f"wrote {dest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
