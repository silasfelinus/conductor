#!/usr/bin/env python3
"""Regenerate projects/art-generate.yaml for the Cthulhuquarium asset set.

WHY THIS EXISTS. The queue used to be hand-written, which meant every fish
prompt lived twice: once in the cthulhuquarium repo's fish/*.yaml (the canonical
bible) and once copied into the queue. The copies drifted the moment the art
direction changed -- 2026-08-25, all 23 bible prompts were rewritten from
silhouette-forward to cartoon and the queue still held the old ones, so a rerun
would have regenerated exactly the photorealistic renders Silas rejected. Fish
prompts are now READ from the bible and never retyped.

Non-fish assets (characters, backgrounds, set pieces, screens) have no bible
entry, so their prompts live in this file. That is the one place to edit them.

Usage:
    python scripts/build_cthulhuquarium_art_queue.py [--bible PATH] [--check]

--check exits 1 if the committed queue does not match what this script would
write, which is how a bible edit that nobody propagated gets caught.
"""
