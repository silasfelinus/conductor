"""Receipt export must reject render-only, mismatched or non-private artwork."""

from pathlib import Path
import importlib.util

import pytest

ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "scripts/export_verified_tactics_arenas.py"
spec = importlib.util.spec_from_file_location("export_evt_arenas", SCRIPT)
assert spec and spec.loader
module = importlib.util.module_from_spec(spec)
spec.loader.exec_module(module)


def test_verified_private_arena_receipts_from_real_ledgers():
    receipts = module.receipts_from_ledgers(module.PROJECT)
    assert {k: (receipts[k]["jobId"], receipts[k]["imageId"]) for k in (
        "last-order", "sunken-street", "unlicensed-rescue"
    )} == {
        "last-order": (71163, 276806),
        "sunken-street": (74323, 277221),
        "unlicensed-rescue": (74324, 277330),
    }
    output = module.render_typescript(receipts)
    assert "GENERATED by conductor/scripts/" in output
    assert "'last-order': {" in output
    assert "imageId: 276806" in output


def test_requested_or_rendered_without_media_proof_is_not_exported(tmp_path):
    ledger = """is_public: false
subjects:
  - asset: every-villain-tactics/maps/last-order-diner
    size: 1152x768
    jobs:
      krea2: 71163
    art:
      krea2:
        status: DONE
        art_image_id: 276806
"""
    (tmp_path / "rendered-only.yaml").write_text(ledger, encoding="utf-8")
    assert module.receipts_from_ledgers(tmp_path) == {}


def test_verified_mismatched_ids_are_rejected(tmp_path):
    ledger = """is_public: false
subjects:
  - asset: every-villain-tactics/maps/last-order-diner
    size: 1152x768
    jobs:
      krea2: 71163
    art:
      krea2:
        status: DONE
        art_image_id: 276806
    media_proof:
      krea2:
        status: VERIFIED
        art_job_id: 71164
        art_image_id: 276806
        downloaded_bytes: 1234
        width: 1152
        height: 768
        aspect_match: true
        blank_check: PASS
        pixel_sha256: aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa
"""
    (tmp_path / "bad-proof.yaml").write_text(ledger, encoding="utf-8")
    with pytest.raises(ValueError, match="inconsistent VERIFIED"):
        module.receipts_from_ledgers(tmp_path)


